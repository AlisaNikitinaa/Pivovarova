-- Демонстрационная таблица для новой учебной базы supermarket.
-- Это пример для запуска приложения, не исходная схема преподавателя.
-- Повторный запуск не удаляет данные и не добавляет те же примеры повторно.
BEGIN;

CREATE TABLE IF NOT EXISTS product (
    prod_id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    prod_name text NOT NULL,
    prod_measure text NOT NULL,
    prod_price numeric(10, 2) NOT NULL CHECK (prod_price >= 0),
    prod_category text NOT NULL
);

INSERT INTO product (prod_name, prod_measure, prod_price, prod_category)
SELECT sample.prod_name, sample.prod_measure, sample.prod_price, sample.prod_category
FROM (VALUES
    ('Молоко', 'л', 95.00, 'молочные'),
    ('Сыр', 'кг', 850.00, 'молочные'),
    ('Помидоры', 'кг', 180.00, 'овощи'),
    ('Огурцы', 'кг', 150.00, 'овощи'),
    ('Хлеб', 'шт', 55.00, 'хлеб')
) AS sample(prod_name, prod_measure, prod_price, prod_category)
WHERE NOT EXISTS (
    SELECT 1 FROM product p
    WHERE p.prod_name = sample.prod_name AND p.prod_category = sample.prod_category
);

COMMIT;
